-- A container header as the real files carry it: two u32 fields, then the
-- payload size as a little-endian u64 at bytes 8 to 15.
local function header(payload)
  local bytes = { 2, 0, 0, 0, 48, 0, 0, 0 }
  for _ = 1, 8 do
    bytes[#bytes + 1] = payload % 256
    payload = math.floor(payload / 256)
  end
  return string.char(unpack(bytes))
end

-- The shape of ED's entry.lua around the one line that matters. update_id
-- comes first on purpose: a pattern that matched the first `id` it saw would
-- take it.
local function entry(id)
  return "if not USE_TERRAIN4 then\n\treturn\nend\n\ntheatre =\n{\n"
    .. "\t['developerName'] = \"x\";\n"
    .. "\t['update_id'] = \"" .. id:upper() .. "_terrain\";\n"
    .. "\t['id'] = \"" .. id .. "\";\n"
    .. "\t['localizedName'] = \"x\";\n"
    .. "} -- end of theatre\n"
end

local BUILD = '{\n "WARNING": "DO NOT EDIT this file. You may break your install!",\n'
  .. ' "version": "2.9.29.27468",\n "timestamp": "20260902-093323",\n'
  .. ' "arch": "x86_64",\n "modules": [\n  "WORLD",\n  "SINAIMAP_terrain"\n ],\n'
  .. ' "launch": "bin/DCS.exe"\n}\n'

local function new_install()
  local fs = FakeFs.new()
  fs.cwd = "C:\\DCS"
  fs.files[INSTALL .. "/autoupdate.cfg"] = BUILD

  -- Sinai: id SinaiMap, a lowercase surface directory, and the siblings that
  -- sit beside each file on the real install.
  local sinai = TERRAINS .. "/Sinai"
  fs.files[sinai .. "/entry.lua"] = entry("SinaiMap")
  fs.files[sinai .. "/surface/SinaiMap.surface5"] = header(43964216) .. string.rep("s", 300)
  fs.files[sinai .. "/surface/SinaiMap.ng5"] = "n"
  fs.files[sinai .. "/surface/SinaiMap.onlay.sup4"] = "o"
  fs.files[sinai .. "/surface/SinaiMap.tile"] = "t"
  fs.files[sinai .. "/roads/SinaiMap.rn4"] = header(200) .. string.rep("r", 184)
  fs.files[sinai .. "/roads/SinaiMap.routes"] = "x"
  fs.files[sinai .. "/Scenes/SinaiMap.scn5"] = header(11888248) .. string.rep("c", 100)
  fs.mtimes[sinai .. "/surface/SinaiMap.surface5"] = 1756800001
  fs.mtimes[sinai .. "/roads/SinaiMap.rn4"] = 1756800003
  fs.mtimes[sinai .. "/Scenes/SinaiMap.scn5"] = 1756800002

  -- Cold War Germany: id GermanyCW, files named after the directory.
  local germany = TERRAINS .. "/GermanyColdWar"
  fs.files[germany .. "/entry.lua"] = entry("GermanyCW")
  fs.files[germany .. "/surface/GermanyColdWar.surface5"] = header(1) .. "g"

  -- Caucasus: id and directory agree, and Surface is capitalized.
  local caucasus = TERRAINS .. "/Caucasus"
  fs.files[caucasus .. "/entry.lua"] = entry("Caucasus")
  fs.files[caucasus .. "/Surface/Caucasus.surface5"] = header(43964216)

  -- Kola: under Mods/terrains, not a theatre.
  fs.files[TERRAINS .. "/Kola/radio.lua"] = "return {}"
  return fs
end

