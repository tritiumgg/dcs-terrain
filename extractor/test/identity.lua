-- Everything here is read off a fake install laid out the way the real one
-- is, including the two things the real one does that the documents did not
-- foresee: a theatre whose data files are named after neither its id nor its
-- directory in any one rule, and a directory under Mods/terrains that is not
-- a theatre at all.

